// TargetStocks 구독 대상 종목에 대한 티커와 종목명 매핑 (100종목)
// 다른 모듈에서 O(1) 조회를 위해 제공
var TargetStocks = make(map[string]string)

func init() {
	for _, s := range TargetStocksList {
		TargetStocks[s.Ticker] = s.Name
	}
}

// GetTargetTickers 구독 대상 종목의 티커 리스트만 반환한다 (웹소켓 구독용)
func GetTargetTickers() []string {
	tickers := make([]string, 0, len(TargetStocksList))
	for _, s := range TargetStocksList {
		tickers = append(tickers, s.Ticker)
	}
	return tickers
}

